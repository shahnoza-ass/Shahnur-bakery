const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const http = require('node:http');
require('dotenv').config();
const mongoose = require('mongoose');
const Product = require('../src/models/Product'), User = require('../src/models/User'), Order = require('../src/models/Order');
const { Promo, Slot, Payment, Counter } = require('../src/models/Commerce');
const workflow = require('../src/services/orderWorkflow'), payments = require('../src/services/payments');
test('commerce: real transactions for customized cakes, slots, bonuses, promos and provider callbacks', { skip: process.env.RUN_DB_INTEGRATION !== '1' }, async () => {
  const dbName = 'bakery_test_' + randomUUID().replace(/-/g, '');
  await mongoose.connect(process.env.MONGODB_URI, { dbName, serverSelectionTimeoutMS: 5000 });
  let server;
  try {
    await Promise.all([Product, User, Order, Promo, Slot, Payment, Counter].map(m => m.init()));
    const user = await User.create({ firstName: 'Test', lastName: 'Buyer', email: 'commerce@example.com', phone: '+998901234567', password: 'Test-password-2026', status: 'approved', bonusBalance: 50000 });
    const cake = await Product.create({ name: 'Custom cake', description: 'Test', category: 'tort', price: 100000, stock: 100, customizable: true, customPricePerKg: 100000, ingredients: 'milk, eggs', allergens: ['milk', 'eggs'], ingredientsVerified: true });
    const clean = await Product.create({ name: 'Verified', description: 'Test', category: 'cookie', price: 10000, stock: 3, allergens: [], ingredientsVerified: true });
    const unknown = await Product.create({ name: 'Unknown', description: 'Test', category: 'cookie', price: 10000, stock: 3 });
    const day = new Date(Date.now() + 4 * 86400000).toISOString().slice(0, 10);
    const data = { items: [{ product: cake.id, quantity: 1 }], deliveryAddress: { street: 'Test street', city: 'Buxoro' }, deliveryDate: day, deliveryTime: '12:00', paymentMethod: 'cash' };
    const actor = { id: user.id, role: 'user' }, staff = { id: user.id, role: 'admin' };
    await Promo.create({ code: 'SWEET10', percent: 10, minAmount: 50000, limit: 5, expiresAt: new Date(Date.now() + 86400000) });
    const order = await workflow.createOrder({ ...data, idempotencyKey: randomUUID(), promoCode: 'SWEET10', bonusUsed: 10000, gift: { enabled: true, recipient: 'Friend', phone: '+998901234568', message: 'Happy birthday', packaging: 'ribbon' } }, user.id);
    assert.equal(order.finalAmount, 95000); assert.equal(order.discount, 20000);
    assert.equal((await User.findById(user.id)).bonusBalance, 40000);
    assert.equal((await Promo.findOne({ code: 'SWEET10' })).used, 1);
    await workflow.changeOrder(order.id, { status: 'cancelled' }, actor);
    await workflow.changeOrder(order.id, { status: 'cancelled' }, actor);
    assert.equal((await User.findById(user.id)).bonusBalance, 50000);
    assert.equal((await Promo.findOne({ code: 'SWEET10' })).used, 0);
    const customized = await workflow.createOrder({ ...data, deliveryTime: '13:00', items: [{ product: cake.id, quantity: 1, customization: { weight: 2, flavor: 'chocolate', cream: 'cheese', decoration: 'berries', inscription: 'Test' } }] }, user.id);
    assert.equal(customized.finalAmount, 305000); assert.equal(customized.items[0].customization.weight, 2);
    for (const status of ['confirmed', 'preparing', 'ready', 'delivered']) await workflow.changeOrder(customized.id, { status }, staff);
    const delivered = await Order.findById(customized.id);
    assert.equal(delivered.bonusEarned, 9150);
    await workflow.changeOrder(customized.id, { status: 'delivered' }, staff);
    assert.equal((await User.findById(user.id)).bonusBalance, 59150);
    const originalStock = (await Product.findById(cake.id)).stock;
    await assert.rejects(workflow.createOrder({ ...data, promoCode: 'MISSING' }, user.id));
    assert.equal((await Product.findById(cake.id)).stock, originalStock, 'invalid promo rolls back inventory');
    const freshParallel = await Promise.all([1, 2].map(() => workflow.createOrder({ ...data, deliveryTime: '17:00' }, user.id)));
    assert.equal(freshParallel.length, 2, 'first concurrent slot initialization does not lose valid orders');
    await Slot.create({ _id: `${day}/14:00`, date: day, time: '14:00', count: 0 });
    process.env.DELIVERY_SLOT_CAPACITY = '1';
    const parallel = await Promise.allSettled([1, 2].map(() => workflow.createOrder({ ...data, deliveryTime: '14:00' }, user.id)));
    assert.equal(parallel.filter(r => r.status === 'fulfilled').length, 1, 'slot capacity survives parallel checkouts');
    delete process.env.DELIVERY_SLOT_CAPACITY;
    process.env.PAYMENTS_ENABLED = 'true'; process.env.PAYME_MERCHANT_ID = 'test-merchant'; process.env.PAYME_SECRET_KEY = 'test-secret';
    const payable = await workflow.createOrder({ ...data, deliveryTime: '15:00', paymentMethod: 'payme' }, user.id);
    const auth = 'Basic ' + Buffer.from('Paycom:test-secret').toString('base64');
    const params = { id: 'payme-test-' + randomUUID(), time: Date.now(), amount: payable.finalAmount * 100, account: { order_id: payable.id } };
    assert.equal((await payments.payme({ method: 'CreateTransaction', params: { ...params, amount: 1 } }, auth)).error.code, -31001);
    assert.equal((await payments.payme({ method: 'CreateTransaction', params }, auth)).result.state, 1);
    assert.equal((await payments.payme({ method: 'PerformTransaction', params: { id: params.id } }, auth)).result.state, 2);
    assert.equal((await payments.payme({ method: 'PerformTransaction', params: { id: params.id } }, auth)).result.state, 2);
    assert.equal((await Order.findById(payable.id)).paymentStatus, 'paid');
    assert.equal((await payments.payme({ method: 'CancelTransaction', params: { id: params.id, reason: 1 } }, auth)).result.state, -2);
    assert.equal((await Order.findById(payable.id)).status, 'refunded');
    process.env.CLICK_MERCHANT_ID = '123'; process.env.CLICK_SERVICE_ID = '456'; process.env.CLICK_SECRET_KEY = 'click-test-secret';
    const clickOrder = await workflow.createOrder({ ...data, deliveryTime: '16:00', paymentMethod: 'click' }, user.id);
    const request = { click_trans_id: '12345', service_id: '456', merchant_trans_id: clickOrder.id, amount: String(clickOrder.finalAmount), action: '0', sign_time: '2026-11-10 12:00:00', error: '0' };
    request.sign_string = payments.clickSignature(request);
    const prepared = await payments.click(request, 0); assert.equal(prepared.error, 0);
    const complete = { ...request, action: '1', merchant_prepare_id: prepared.merchant_prepare_id }; complete.sign_string = payments.clickSignature(complete);
    assert.equal((await payments.click({ ...complete, sign_string: 'bad' }, 1)).error, -1);
    assert.equal((await payments.click(complete, 1)).error, 0);
    assert.equal((await payments.click(complete, 1)).error, -4);
    assert.equal((await Order.findById(clickOrder.id)).paymentStatus, 'paid');
    const app = require('../src/app'); server = http.createServer(app); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = 'http://127.0.0.1:' + server.address().port;
    const response = await fetch(base + '/api/products?excludeAllergens=milk&limit=100'); const list = await response.json();
    assert.ok(list.data.some(p => p._id === clean.id)); assert.ok(!list.data.some(p => [cake.id, unknown.id].includes(p._id)));
    assert.equal((await fetch(base + '/api/commerce/admin/insights?from=' + day + '&to=' + day)).status, 401);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    assert.match(dbName, /^bakery_test_[a-f\d]{32}$/); await mongoose.connection.dropDatabase(); await mongoose.disconnect();
  }
});
