const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const { randomUUID } = require('node:crypto');
require('dotenv').config();
const mongoose = require('mongoose');
const User = require('../src/models/User');
const Product = require('../src/models/Product');
const Order = require('../src/models/Order');
const Chat = require('../src/models/Chat');
const Review = require('../src/models/Review');
const ContactMessage = require('../src/models/ContactMessage');
const workflow = require('../src/services/orderWorkflow');

test('real MongoDB: authentication, transactional inventory, chat and password recovery', { skip: process.env.RUN_DB_INTEGRATION !== '1' }, async t => {
  const databaseName = 'bakery_test_' + randomUUID().replace(/-/g, '');
  assert.match(databaseName, /^bakery_test_[a-f\d]{32}$/);
  await mongoose.connect(process.env.MONGODB_URI, { dbName: databaseName, serverSelectionTimeoutMS: 5000 });
  let server;
  let io;
  const sockets = [];
  try {
    const hello = await mongoose.connection.db.admin().command({ hello: 1 });
    assert.ok(hello.setName || hello.msg === 'isdbgrid', 'integration tests require a replica set');
    await Promise.all([User, Product, Order, Chat, Review, ContactMessage].map(model => model.init()));
    const emailService = require('../src/services/emailService');
    let resetToken;
    t.mock.method(emailService, 'sendWelcomeEmail', async () => true);
    t.mock.method(emailService, 'sendPasswordResetEmail', async (_email, _name, token) => { resetToken = token; return true; });
    t.mock.method(require('../src/services/notificationService'), 'notifyNewOrder', async () => ({ success: true }));
    const app = require('../src/app');
    server = http.createServer(app);
    io = require('../server').configureSockets(server);
    app.set('io', io);
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = 'http://127.0.0.1:' + server.address().port;
    const request = async (route, method = 'GET', body, token) => {
      const response = await fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      return { status: response.status, body: await response.json() };
    };
    const credentials = { email: 'buyer@example.com', password: 'Test-password-2026' };
    const registration = await request('/api/auth/register', 'POST', { ...credentials, confirmPassword: credentials.password, firstName: 'Test', lastName: 'Buyer', phone: '+998901234567' });
    assert.equal(registration.status, 201);
    let token;
    for (let attempt = 0; attempt < 2; attempt++) {
      const login = await request('/api/auth/login', 'POST', credentials);
      assert.equal(login.status, 200, 'password must remain valid after login saves lastLogin');
      token = login.body.data.token;
    }
    const user = await User.findOne({ email: credentials.email });
    const admin = await User.create({ email: 'staff@example.com', password: 'Test-staff-password', firstName: 'Staff', lastName: 'Test', phone: '+998901234568', role: 'admin', status: 'approved' });
    const product = await Product.create({ name: 'Test cake', description: 'Integration test fixture', category: 'tort', price: 150000, stock: 3 });
    const unavailable = await Product.create({ name: 'No stock', description: 'Integration test fixture', category: 'tort', price: 50000, stock: 0 });
    const data = { items: [{ product: product.id, quantity: 1 }], deliveryAddress: { street: 'Test street', city: 'Buxoro' }, deliveryDate: new Date(Date.now() + 86400000).toISOString(), deliveryTime: '12:00', paymentMethod: 'cash' };
    assert.equal((await request('/api/products')).status, 200);
    assert.equal((await request('/ready')).status, 200);
    assert.equal((await request('/api/orders', 'POST', { ...data, discount: 150000 }, token)).status, 400);
    const brokenOrder = { ...data, items: [...data.items, { product: unavailable.id, quantity: 1 }] };
    await assert.rejects(workflow.createOrder(brokenOrder, user.id), { status: 409 });
    assert.equal((await Product.findById(product.id)).stock, 3, 'failed checkout must roll back earlier reservations');
    const key = randomUUID();
    const duplicate = await Promise.all([workflow.createOrder({ ...data, idempotencyKey: key }, user.id), workflow.createOrder({ ...data, idempotencyKey: key }, user.id)]);
    assert.equal(duplicate[0].id, duplicate[1].id);
    assert.equal((await Product.findById(product.id)).stock, 2);
    const parallel = await Promise.allSettled(Array.from({ length: 3 }, () => workflow.createOrder(data, user.id)));
    assert.equal(parallel.filter(result => result.status === 'fulfilled').length, 2);
    assert.equal((await Product.findById(product.id)).stock, 0, 'parallel checkouts cannot oversell');
    const actor = { id: user.id, role: 'user' };
    await Promise.all([workflow.changeOrder(duplicate[0].id, { status: 'cancelled' }, actor), workflow.changeOrder(duplicate[0].id, { status: 'cancelled' }, actor)]);
    assert.equal((await Product.findById(product.id)).stock, 1, 'concurrent cancellation restores only once');
    const httpKey = randomUUID();
    const httpOrder = await request('/api/orders', 'POST', { ...data, idempotencyKey: httpKey }, token);
    assert.equal(httpOrder.status, 201);
    assert.equal(httpOrder.body.data.finalAmount, 150000);
    const retry = await request('/api/orders', 'POST', { ...data, idempotencyKey: httpKey }, token);
    assert.equal(retry.body.data._id, httpOrder.body.data._id);
    const support = await request('/api/chat/support', 'POST', {}, token);
    assert.equal(support.status, 200);
    const chatId = support.body.data._id;
    const message = await request('/api/chat/' + chatId + '/messages', 'POST', { content: 'Test support message' }, token);
    assert.equal(message.status, 201);
    assert.equal((await Chat.findById(chatId)).messages.length, 1);
    const stranger = await User.create({ email: 'stranger@example.com', password: 'Stranger-password', firstName: 'Other', lastName: 'User', phone: '+998901234569', status: 'approved' });
    const { generateToken } = require('../src/config/jwt');
    const strangerToken = generateToken(stranger.id, stranger.tokenVersion);
    assert.equal((await request('/api/chat/' + chatId, 'GET', null, strangerToken)).status, 404);
    assert.equal((await request('/api/chat/' + chatId + '/messages', 'POST', { content: 'Forbidden' }, strangerToken)).status, 403);
    const socketClient = require('../../shahnur-bakery-frontend/node_modules/socket.io-client');
    const connectSocket = async authToken => {
      const client = socketClient.io(base, { auth: { token: authToken }, transports: ['websocket'], reconnection: false, timeout: 3000 });
      sockets.push(client);
      await new Promise((resolve, reject) => { client.once('connect', resolve); client.once('connect_error', reject); });
      return client;
    };
    const outsiderSocket = await connectSocket(strangerToken);
    const joined = await outsiderSocket.timeout(3000).emitWithAck('join_chat', chatId);
    assert.equal(joined.success, false);
    const forbidden = await outsiderSocket.timeout(3000).emitWithAck('send_message', { chatId, content: 'Forbidden socket message' });
    assert.equal(forbidden.success, false);
    assert.equal((await Chat.findById(chatId)).messages.length, 1);
    const buyerSocket = await connectSocket(token);
    assert.equal((await buyerSocket.timeout(3000).emitWithAck('send_message', { chatId, content: 'Persisted socket message' })).success, true);
    assert.equal((await Chat.findById(chatId)).messages.length, 2);
    const adminToken = generateToken(admin.id, admin.tokenVersion);
    assert.equal((await request('/api/admin/users/' + admin.id, 'PUT', { role: 'superadmin' }, adminToken)).status, 403);
    assert.equal((await request('/api/chat/' + chatId + '/read', 'PUT', {}, adminToken)).status, 200);
    assert.equal((await Chat.findById(chatId)).unreadCount.get(admin.id), 0);
    assert.equal((await request('/api/contact', 'POST', { name: 'Test', email: 'sender@example.com', message: 'Contact integration test' })).status, 201);
    assert.equal(await ContactMessage.countDocuments(), 1);
    assert.equal((await request('/api/auth/forgot-password', 'POST', { email: credentials.email })).status, 200);
    assert.match(resetToken, /^[a-f\d]{64}$/);
    const newPassword = 'New-test-password-2026';
    assert.equal((await request('/api/auth/reset-password/' + resetToken, 'POST', { password: newPassword, confirmPassword: newPassword })).status, 200);
    assert.equal((await request('/api/auth/reset-password/' + resetToken, 'POST', { password: newPassword, confirmPassword: newPassword })).status, 400);
    assert.equal((await request('/api/auth/me', 'GET', null, token)).status, 401);
    assert.equal((await request('/api/auth/login', 'POST', { ...credentials, password: newPassword })).status, 200);
  } finally {
    for (const socket of sockets) socket.disconnect();
    if (io) await new Promise(resolve => io.close(resolve));
    if (server?.listening) await new Promise(resolve => server.close(resolve));
    // Only this randomly named test database is ever removed.
    if (mongoose.connection.db?.databaseName === databaseName && /^bakery_test_[a-f\d]{32}$/.test(databaseName)) await mongoose.connection.db.dropDatabase();
    await mongoose.disconnect();
  }
});
